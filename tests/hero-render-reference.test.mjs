import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const html=readFileSync(new URL('../public/index.html',import.meta.url),'utf8');
const css=readFileSync(new URL('../public/code-hero.css',import.meta.url),'utf8');
const hero=html.match(/<section class="sd-code-hero wrap" id="home"[\s\S]*?<\/section>/)?.[0];
assert.ok(hero,'Code-only Hero must be the live home section');
assert.match(hero,/<h1 class="sdh-title" id="sdh-title">/);
assert.match(hero,/<span>Phong cách<\/span><span class="sdh-em">Đẳng cấp<\/span><span>từ da cá sấu<\/span>/);
assert.match(hero,/<a class="sdh-cta sdh-cta--zalo" href="https:\/\/zalo\.me\/0827049192" target="_blank" rel="noopener noreferrer"[^>]*>Tư vấn đặt sản phẩm theo yêu cầu qua Zalo/);
assert.match(hero,/<span class="sdh-glass-label">SINDAREALEST · SIGNATURE<\/span><span class="sdh-glass-message"><span>Da cá sấu thật<\/span><span>Phong cách sống thật<\/span><\/span>/);
assert.match(css,/\.sd-code-hero \.sdh-glass-label\{[^}]*translateY\(-4px\)/);
assert.match(css,/\.sd-code-hero \.sdh-glass-message span:first-child/);
assert.match(css,/@keyframes sdh-cta-border-pulse/);
assert.match(css,/@media\(prefers-reduced-motion:reduce\)\{[\s\S]*?\.sdh-cta--zalo::before\{animation:none/);
assert.doesNotMatch(hero,/<(?:picture|img|canvas|video)\b|style=|\.png|\.jpe?g|\.webp/);
assert.doesNotMatch(css,/url\(|!important/);
assert.match(css,/\.sd-code-hero \.sdh-stage::before/);
assert.match(css,/\.sd-code-hero \.sdh-bubble--low\{right:auto;top:65%/);
assert.doesNotMatch(hero,/sdh-kicker/);
assert.match(css,/html\.dark \.sd-code-hero/);
assert.match(css,/font:700 clamp\(39px,4vw,59px\)/);
assert.match(css,/@media\(max-width:760px\)/);
assert.match(css,/height:clamp\(236px,66vw,270px\)/);
assert.match(css,/height:420px/);
assert.match(css,/backdrop-filter:blur\(14px\)/);
assert.match(html,/<link rel="stylesheet" href="\/code-hero\.css\?v=20261026-2">/);
assert.doesNotMatch(html,/<picture class="hero-reference-art"/);
assert.doesNotMatch(html,/id="heroProductImage"/);
assert.doesNotMatch(html,/HERO V2 — compact physical marble plinth|HERO REBUILD V8|HERO RENDER PARITY V7/,'Retired image-based HERO CSS must not return');
// Retired image-HERO selectors are not used by the live code-only Hero.
assert.equal(html.includes('id="heroProductImage"'), false);
assert.equal(html.includes('class="hero"'), false);
assert.equal(html.includes('.hero-visual{'), false);
assert.equal(html.includes('.hero-copy{'), false);
assert.equal(html.includes('#home.hero.wrap{'), false);
console.log('PASS: code-only hero contract, copy, breakpoints and theme variants');