import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const html=readFileSync(new URL('../public/index.html',import.meta.url),'utf8');
const css=readFileSync(new URL('../public/code-hero.css',import.meta.url),'utf8');
const hero=html.match(/<section class="sd-code-hero wrap" id="home"[\s\S]*?<\/section>/)?.[0];
assert.ok(hero,'Code-only Hero must be the live home section');
assert.match(hero,/<h1 class="sdh-title" id="sdh-title">/);
assert.match(hero,/<span>Phong cách<\/span><span class="sdh-em">Đẳng cấp<\/span><span>từ da cá sấu<\/span>/);
assert.match(hero,/href="#products">Khám phá ngay/);
assert.doesNotMatch(hero,/<(?:picture|img|canvas|video)\b|style=|\.png|\.jpe?g|\.webp/);
assert.doesNotMatch(css,/url\(|!important/);
assert.match(css,/html\.dark \.sd-code-hero/);
assert.match(css,/@media\(max-width:760px\)/);
assert.match(css,/height:clamp\(236px,66vw,270px\)/);
assert.match(css,/height:420px/);
assert.match(css,/backdrop-filter:blur\(14px\)/);
assert.match(html,/<link rel="stylesheet" href="\/code-hero\.css\?v=20261026-1">/);
assert.doesNotMatch(html,/<picture class="hero-reference-art"/);
assert.doesNotMatch(html,/id="heroProductImage"/);
console.log('PASS: code-only hero contract, copy, breakpoints and theme variants');