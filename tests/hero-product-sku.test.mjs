import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const html=readFileSync(new URL('../public/index.html',import.meta.url),'utf8');
const css=readFileSync(new URL('../public/code-hero.css',import.meta.url),'utf8');
const live=html.match(/<section class="sd-code-hero wrap" id="home"[\s\S]*?<\/section>/)?.[0]||'';
assert.ok(live);
assert.doesNotMatch(live,/<img\b|<picture\b|background-image|hero-reference-art|heroProductImage/);
assert.doesNotMatch(html,/function syncHeroProductImage\(|syncHeroProductImage\(\);/);
assert.match(live,/class="sdh-glass-card"/);
assert.match(live,/class="sdh-stage"/);
assert.match(live,/class="sdh-orbit/);
assert.match(live,/class="sdh-cta" href="#products"/);
assert.match(css,/\.sd-code-hero \.sdh-title/);
assert.doesNotMatch(css.replace(/\/\*[\s\S]*?\*\//g,''),/#[a-z-]*home|\.hero-copy|\.hero-visual|!important/);
const activeClasses=[...live.matchAll(/class="([^"]+)"/g)].flatMap(m=>m[1].split(/\s+/));
assert.ok(!activeClasses.some(c=>['hero','hero-copy','hero-visual','hero-reference-art','hero-pedestal-art','hero-visual-glow'].includes(c)));
assert.ok(html.includes('@font-face{font-family:SD Sans')&&html.includes('@font-face{font-family:SD Serif'));
assert.match(html,/<meta charset="utf-8">/);
console.log('PASS: no catalog/photo dependency, zero active legacy hero classes, Vietnamese fonts');