import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {execFileSync} from 'node:child_process';
const read=path=>readFileSync(new URL('../'+path,import.meta.url),'utf8');
test('Owner-controlled material photos are config-driven and have no manual controls',()=>{
 const page=read('public/index.html'),js=read('public/material-gallery.js'),css=read('public/material-gallery.css');
 const config=JSON.parse(read('public/images/crocodile-leather/gallery.json'));
 assert.ok(Array.isArray(config.images)&&config.images.length>0);
 assert.ok(config.images.every(s=>/^[a-zA-Z0-9][a-zA-Z0-9._-]{0,99}\.(?:avif|webp|jpe?g|png)$/i.test(s)));
 assert.equal(new Set(config.images).size,config.images.length);
 assert.equal(config.intervalMs,1500);
 assert.match(page,/id="materialTile"[^>]+data-reveal/);
 assert.match(page,/id="materialGallery" aria-hidden="true"/);
 assert.match(page,/src="\/material-gallery.js" defer/);
 assert.match(page,/href="\/material-gallery.css"/);
 assert.match(js,/setInterval\(\(\)=>\{/);
 assert.match(js,/\},1500\)/);
 assert.doesNotMatch(js,/createElement\(['"]button['"]\)/);
 assert.match(js,/if\(!names\.length\)return/);
 assert.match(js,/if\(!loaded\.length\)return/);
 assert.match(css,/#materialTile\.has-real-material-gallery .material-photo/);
 execFileSync(process.execPath,['--check',new URL('../public/material-gallery.js',import.meta.url).pathname]);
});
test('Theme crossfades smoothly with one synchronized duration and no stagger',()=>{
 const page=read('public/index.html'),css=read('public/material-gallery.css');
 assert.match(page,/function applyThemeMode\(mode,animate=true\)/);
 assert.match(page,/root\.classList\.toggle\('theme-transitioning',smooth\)/);
 assert.match(page,/setTimeout\(\(\)=>root\.classList\.remove\('theme-transitioning'\),290\)/);
 assert.doesNotMatch(page,/function applyThemeMode[^\n]*void document\.body\.offsetHeight/);
 assert.match(css,/html\.theme-transitioning body \.theme-bg\{[\s\S]*?opacity \.22s/);
 assert.match(css,/#materialTile \.sd-material-slide\{[\s\S]*?opacity \.58s/);
 assert.match(css,/#materialTile::before\{/);
 assert.match(css,/#materialTile\.has-real-material-gallery::before/);
 assert.match(css,/#materialTile\.has-real-material-gallery::after/);
 assert.match(css,/background:none!important;/);
 assert.match(css,/text-shadow:0 1px 3px/);
 assert.match(css,/html body \.nav-wrap \.nav,[\s\S]*?transition-duration:\.22s!important;/);
 assert.match(css,/html\.theme-transitioning body \.nav-wrap \.nav/);
 assert.match(css,/html\.theme-transitioning,html\.theme-transitioning body\{[\s\S]*?transition:none!important;/);
 assert.match(page,/const themeMeta=document\.querySelector\('meta\[name="theme-color"\]'\)/);
 assert.doesNotMatch(page,/transition:background-color 1\.15s/,'Stale slow theme CSS must not reappear');
 assert.doesNotMatch(page,/html\.theme-transitioning \.nav,html\.theme-transitioning \.glass/,'Duplicate theme transition overrides must not reappear');
 assert.match(css,/#order,#featured,#collections,#products,#siteFooter\\{[\\s\\S]*?content-visibility:auto;/);
});
