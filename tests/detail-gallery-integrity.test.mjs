import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';

const html = readFileSync(new URL('../public/index.html', import.meta.url), 'utf8');
const styles = readFileSync(new URL('../public/ui/storefront.css', import.meta.url), 'utf8');
const count = text => html.split(text).length - 1;

assert.equal(count('id="detailZoom"'), 1, 'The detail viewer must expose exactly one full-image control.');
assert.equal(count('id="sdFullscreenViewer"'), 1, 'There must be exactly one full-screen viewer.');
assert.equal(count('id="sdFullscreenImage"'), 1, 'The fullscreen gallery needs one primary image layer.');
assert.equal(count('id="sdFullscreenImageNext"'), 1, 'The fullscreen gallery needs a second preloaded layer to prevent blank frames.');
assert.match(html, /id="detailZoom" aria-label="Xem toàn ảnh ở chế độ toàn màn hình"/);
assert.match(html, /function sizeFullscreenFrame\([^)]*\)/);
assert.match(html, /function setFullscreenPhoto\(/);
assert.match(html, /function renderFullscreenThumbs\(/);
assert.match(html, /function openFullscreenImage\(\)/);
assert.match(html, /function closeFullscreenImage\(\)/);
assert.match(html, /\$\(['"]#detailZoom['"]\)\.addEventListener\(['"]click['"],openFullscreenImage\)/);
assert.match(html, /\$\(['"]#detailMainImage['"]\)\.addEventListener\(['"]click['"]/);
assert.match(html, /\$\(['"]#sdFullscreenFrame['"]\)\.addEventListener\(['"]pointerup['"]/);
assert.match(html, /\$\(['"]#sdFullscreenPrev['"]\)\.addEventListener\(['"]click['"]/);
assert.match(html, /\$\(['"]#sdFullscreenNext['"]\)\.addEventListener\(['"]click['"]/);
assert.match(html, /\$\(['"]#sdFullscreenThumbs['"]\)\.addEventListener\(['"]click['"]/);
assert.match(html, /id="detailPrev" aria-label="Ảnh sản phẩm trước"><svg/);
assert.match(html, /id="detailNext" aria-label="Ảnh sản phẩm tiếp theo"><svg/);
assert.match(html, /id="sdFullscreenPrev" aria-label="Ảnh trước"><svg/);
assert.match(html, /id="sdFullscreenNext" aria-label="Ảnh tiếp theo"><svg/);
assert.match(html, /sdGalleryOutLeft/);
assert.match(html, /sdGalleryInRight/);
assert.match(styles, /@media\(max-width:760px\)/);
assert.match(styles, /@media\(max-width:390px\)/);
assert.match(html, /stage:document\.querySelector\('#sdFullscreenFrame'\)/);
assert.doesNotMatch(html, /id="sdFullscreenWatermark"/, 'Fullscreen watermark must use the live settings helper.');
assert.ok(html.includes("$('#sdFullscreenViewer').classList.contains('open')"), 'Autoplay should pause while full-screen controls are open.');


const fullscreenTransitionStart = html.indexOf('function setFullscreenPhoto(');
const fullscreenTimingConstant = html.lastIndexOf('const FULLSCREEN_SLIDE_MS=300', fullscreenTransitionStart);
assert.notEqual(fullscreenTimingConstant, -1, 'The fullscreen transition duration constant must be declared before the transition handler.');
const fullscreenTransition = html.slice(
  fullscreenTimingConstant,
  html.indexOf('function renderFullscreenThumbs(')
);
assert.equal(count('function arrowIcon('), 1, 'Arrow SVG markup must be generated by one shared helper.');
assert.equal((styles.match(/--gallery-glass:rgba/g) || []).length, 2, 'Gallery glass must define one material for light mode and one for dark mode.');
assert.match(styles, /html\.dark\{[^}]*--gallery-glass:rgba\(245,239,226,\.14\);--gallery-glass-border:rgba\(255,255,255,\.38\)/);
assert.match(styles, /\.slide-count,\.featured-image-count,\.detail-image-count,\.sd-fullscreen-count\{[^}]*backdrop-filter:blur\(18px\)/);
assert.match(styles, /\.detail-gallery-arrow:active,\.sd-fullscreen-arrow:active\{transform:translateY\(-50%\) scale\(\.85\)/);
assert.match(styles, /\.featured-arrow:active,\.slide-controls button:active,\.page-btn\.page-arrow:active\{transform:scale\(\.85\)/);
assert.match(styles, /\.sd-fullscreen-image\.sd-slide-out-left\{animation:sdFullscreenOutLeft 300ms/);
assert.match(styles, /\.sd-fullscreen-image\.sd-slide-in-right\{animation:sdFullscreenInRight 300ms/);
assert.match(html, /function activeFullscreenImage\(\)/);
assert.match(html, /incoming\.onload=finishLoad;incoming\.onerror=failLoad;incoming\.src=next/);
assert.match(html, /active\.classList\.remove\('is-active'\);incoming\.classList\.add\('is-active'\)/);
assert.match(styles, /\.sd-fullscreen-frame\{[^}]*background:rgba\(245,239,226,\.035\)/);
assert.match(fullscreenTransition, /const FULLSCREEN_SLIDE_MS=300/);
assert.match(fullscreenTransition, /incoming\.onload=finishLoad/);
assert.match(fullscreenTransition, /fullscreenAnimationTimer=setTimeout/);
assert.doesNotMatch(fullscreenTransition, /\b(?:150|230|620)\b/, 'Fullscreen transitions must not use conflicting legacy timings.');
assert.doesNotMatch(html, /id="artPrev"[^>]*>‹/);
assert.doesNotMatch(html, /class="featured-arrow[^>]*>‹/);
assert.doesNotMatch(html, /data-page="(?:prev|next)"[^>]*>‹/);


assert.match(styles, /\.detail-zoom-btn,\.detail-gallery-arrow,\.featured-arrow,\.slide-controls button,\.page-btn\.page-arrow,\.sd-fullscreen-close,\.sd-fullscreen-arrow\{[^}]*background:var\(--gallery-glass\)/, 'All arrow controls must use the shared glass material.');
assert.match(styles, /\.detail-zoom-btn,\.detail-gallery-arrow,\.featured-arrow,\.slide-controls button,\.page-btn\.page-arrow,\.sd-fullscreen-close,\.sd-fullscreen-arrow\{[^}]*background:var\(--gallery-glass\)/);
assert.match(styles, /\.sd-fullscreen-viewer\{[^}]*background:rgba\(0,0,0,\.30\)/);
assert.match(styles, /\.sd-fullscreen-viewer\{[^}]*backdrop-filter:blur\(8px\)/);
assert.doesNotMatch(styles, /\.sd-fullscreen-viewer\{[^}]*background:rgba\(8,8,8,\.94\)/, 'Fullscreen must not use an almost opaque black backdrop.');
assert.match(styles, /\.detail-gallery-arrow:active,\.sd-fullscreen-arrow:active\{transform:translateY\(-50%\) scale\(\.85\)/);
assert.match(styles, /\.featured-arrow:active,\.slide-controls button:active,\.page-btn\.page-arrow:active\{transform:scale\(\.85\)/);


assert.doesNotMatch(styles, /id="sd-unified-arrow-glass-final"/, "Arrow glass rules should be consolidated rather than duplicated in a late override.");
assert.match(styles, /\.detail-gallery-arrow:hover,\.featured-arrow:hover,\.slide-controls button:hover,\.page-btn\.page-arrow:hover,\.sd-fullscreen-arrow:hover\{background:rgba\(157,119,58,\.72\)/);
assert.match(styles, /@media\(hover:none\)\{\s*\.detail-gallery-arrow:hover:not\(:active\),\.sd-fullscreen-arrow:hover:not\(:active\)\{transform:translateY\(-50%\) scale\(1\)\}/, 'Touch hover must not leave gallery arrows enlarged after tap');
assert.match(styles, /\.featured-arrow:hover:not\(:active\),\.slide-controls button:hover:not\(:active\),\.page-btn\.page-arrow:hover:not\(:active\)\{transform:scale\(1\)\}/, 'Touch hover must not leave carousel and pagination arrows enlarged after tap');
assert.match(styles, /\.detail-gallery-arrow:hover:not\(:active\),\.featured-arrow:hover:not\(:active\),\.slide-controls button:hover:not\(:active\),\.page-btn\.page-arrow:hover:not\(:active\),\.sd-fullscreen-arrow:hover:not\(:active\)\{background:var\(--gallery-glass\);border-color:var\(--gallery-glass-border\)\}/, 'Touch hover must not leave the gold hover surface stuck after tapping');


