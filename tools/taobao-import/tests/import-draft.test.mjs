class FakeDb {
  constructor(){this.products=new Map();this.logs=[];this.nextError=null;}
  prepare(sql){
    const db=this;
    return {bind(...args){
      return {async first(){if(sql.startsWith('SELECT * FROM products WHERE id='))return db.products.get(args[0])||null;throw Error('unexpected first '+sql);},
        async all(){if(sql.startsWith('SELECT sku FROM products WHERE sku LIKE'))return {results:[...db.products.values()].map(p=>({sku:p.sku}))};throw Error('unexpected all '+sql);},
        _statement:{sql,args}};
    }};
  }
  async batch(statements){
    const product=statements[0]._statement;
    if(!product.sql.includes('INTO products'))throw Error('Wrong insert');
    const [id,slug,sku,skuVerified,title,category,categoryLabel,description,price,stock,published,images_json,sourcePriceConfirmed,sortOrder,fulfillmentType]=product.args;
    if(this.products.has(id))throw Error('UNIQUE constraint failed: products.id');
    if([...this.products.values()].some(p=>p.sku===sku))throw Error('UNIQUE constraint failed: products.sku');
    this.products.set(id,{id,slug,sku,sku_verified:skuVerified,title,category,category_label:categoryLabel,description,price,stock,published,images_json,source_price_confirmed:sourcePriceConfirmed,sort_order:sortOrder,fulfillment_type:fulfillmentType});
    this.logs.push(statements[1]._statement);
  }
}
